export function getUniversityByCode(code: string): KarnatakaUniversitySeed | undefined {
  return KARNATAKA_UNIVERSITIES.find((u) => u.code === code);
}

export function getTotalEstimatedColleges(): { min: number; max: number } {
  return KARNATAKA_UNIVERSITIES.reduce(
    (acc, u) => ({
      min: acc.min + u.collegeCountMin,
      max: acc.max + u.collegeCountMax,
    }),
    { min: 0, max: 0 }
  );
}

export interface PrioritySummaryItem {
  priority: number;
  label: string;
  universities: number;
  collegesMin: number;
  collegesMax: number;
}

export function getPrioritySummary(): PrioritySummaryItem[] {
  const priorities = [1, 2, 3, 4, 5];
  const labels: Record<number, string> = {
    1: "Phase 1 — Critical",
    2: "Phase 2 — High",
    3: "Phase 3 — Medium",
    4: "Phase 4 — Low",
    5: "Phase 5 — Future",
  };

  return priorities.map((p) => {
    const unis = KARNATAKA_UNIVERSITIES.filter((u) => u.priority === p);
    return {
      priority: p,
      label: labels[p],
      universities: unis.length,
      collegesMin: unis.reduce((s, u) => s + u.collegeCountMin, 0),
      collegesMax: unis.reduce((s, u) => s + u.collegeCountMax, 0),
    };
  });
}