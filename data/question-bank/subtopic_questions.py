"""Sub-topic questions for the B.Com / BA / B.Sc seed bank.

These extend the original topic-level bank (bcom_questions.py and friends) with
questions authored *per sub-topic*, so the bank covers the third tier of the
hierarchy that the universal question bank stores as `subTopicId`:

    subject → topic (CSV `unit`) → sub-topic (CSV `subtopic`)

Every sub-topic named here must be declared in structure.py — the generator
rejects anything else, which is what stops a typo from splitting one concept
into two phantom sub-topics in the bank's filters.

Format rules (the app's CSV parsers split on a raw comma):
  * NO commas and NO double quotes inside any field
  * NO pipe characters in text or options (pipe separates MCQ options)
  * mcq needs 4 options and a key of A / B / C / D
  * true_false key is exactly True or False
  * numerical key is a bare number
  * short_answer / long_answer put the expected answer in `correct`
  * one line per question
"""


def SQ(text, type_, difficulty, marks, options, correct, explanation=""):
    return {
        "text": text,
        "type": type_,
        "difficulty": difficulty,
        "marks": marks,
        "options": options,
        "correct": correct,
        "explanation": explanation,
    }


