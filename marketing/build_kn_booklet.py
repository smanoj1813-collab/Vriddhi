M = 18
W, H = 210, 297
CW = W - 2 * M
MPU = 72 / 25.4  # mm -> pt


class Page:
    def __init__(self, pdf):
        self.pdf = pdf
        self.canvas = TextCanvas(W * MPU, H * MPU)

    def t(self, x, y, w, text, size, color, font=KN_REG, align="L", line_h=None):
        """Place text (mm coords). Returns height consumed in mm."""
        lh = line_h * MPU if line_h else None
        h = self.canvas.text(x * MPU, y * MPU, w * MPU, text, size, hbf_pdf(color),
                             ttf=font, align=align, line_h=lh)
        return h / MPU

    def nlines(self, w, text, size, font=KN_REG):
        return len(self.canvas.wrap(font, size, text, w * MPU))

    def header(self, kicker_t, title):
        self.t(18, 16, 174, kicker_t, 9, TEAL_D, KN_SB)
        self.pdf.set_fill_color(*TEAL)
        self.pdf.rect(18, 16 + 4.2, 8, 0.8, style="F")
        self.t(18, 16 + 8, 174, title, 17.5, SLATE, KN_SB)

    def footer(self):
        self.t(18, H - 9, 140, "ವೃದ್ಧಿ — ಭಾರತದ ಕಾಲೇಜುಗಳ ಶೈಕ್ಷಣಿಕ ಆಪರೇಟಿಂಗ್ ಸಿಸ್ಟಮ್",
               7.5, SLATE_4)
        self.t(192, H - 9, 0, str(self.pdf.page_no()), 7.5, SLATE_4, align="R")

    def finish(self):
        buf = io.BytesIO()
        self.canvas.render().save(buf, "PNG")
        buf.seek(0)
        self.pdf.image(buf, x=0, y=0, w=W)


def bg(pdf, color):
    pdf.set_fill_color(*color)
    pdf.rect(0, 0, W, H, style="F")


pdf = Doc("P", "mm", "A4")
pdf.footer = lambda: None  # disable auto English footer; KN footer drawn per page


def new_page(color):
    pdf.add_page()
    bg(pdf, color)
    return Page(pdf)


def flow_items(p, x, y, w, items, lead_size=10.8, desc_size=9.6):
    """Lead + desc items; desc lines measured. Returns y after last item."""
    for lead, desc in items:
        p.pdf.dot(x + 1.1, y + 1.5, d=1.7)
        p.t(x + 5, y, w - 5, lead, lead_size, SLATE, KN_SB)
        n = p.nlines(w - 5, desc, desc_size)
        p.t(x + 5, y + 5.8, w - 5, desc, desc_size, SLATE_5, line_h=4.6)
        y += 5.8 + n * 4.6 + 5.2
    return y


